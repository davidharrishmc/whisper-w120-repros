// zero (allowed) or, if mip[i] and mie[i] can both be 1 for some i >= 32, interrupt i is pending and enabled:
// mtopi is nonzero with IID = an interrupt >= 32 (MSLevel.adoc:428-432) and, with mstatus.MIE = 1, the interrupt
// traps (MSLevel.adoc:226-230; machine.adoc trap conditions, bit i of mip/mie <-> cause i).
#if __riscv_xlen == 32
  csrci mstatus, 8
  csrw mie, x0
  csrw mideleg, x0
