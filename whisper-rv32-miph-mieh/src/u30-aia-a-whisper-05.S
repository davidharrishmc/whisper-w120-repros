// verify v12, u30-aia-a-whisper-05 (Whisper RV32): miph/mieh bits that are writable in both registers make interrupt
// 32+k pending and enabled, so mtopi must report it and it must trap with MIE = 1 (or the bits must be read-only 0).
// Spec: AIA CSRs.adoc:12-15 (high halves are bits 63:32; "may all be merely read-only zeros"), MSLevel.adoc:226-230
//   (trap conditions on mip/mie bits), :428-432 (mtopi); ISA priv/machine.adoc (bit i of mip/mie <-> cause i).
// Expected: either miph & mieh = 0 after writing all ones, or mtopi.IID >= 32 and an interrupt trap with code >= 32.
// Source: walk/u30-aia-a-whisper-candidates.csv (05), work/u30-aia-a-whisper/walku30w-pb.S (C7).

